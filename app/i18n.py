def resolve_language(lang: str | None, lang_cookie: str | None) -> str:
    candidate = (lang or lang_cookie or DEFAULT_LANGUAGE).strip().lower()
    return candidate if candidate in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def get_language_pack(lang: str) -> dict[str, str]:
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE]).copy()
